#!/usr/bin/env python3
"""Turn batch 5 (A) and batch 6 (C / A x C) results JSON into RESULTS3.md tables.
Pure reads -- no API. Auto-derives the headline numbers."""
from __future__ import annotations

import json
from pathlib import Path

R = Path(__file__).parent / "results"
OUT = R / "RESULTS3.md"
VEC = ["V1_fact", "V2_sentiment", "V3_selective", "V4_structured", "V5_multisource"]


def _load(name):
    p = R / f"{name}_results.json"
    return json.loads(p.read_text()) if p.exists() else None


def section_A(w):
    d = _load("n5_pipeline")
    if not d:
        w("_(batch 5 A results not found)_\n")
        return
    s = d["summary"]
    m = d["meta"]
    w("## A — Multi-Agent Pipeline Attack Propagation\n")
    w(f"\n_{m['n_rows']} cells · {len(m['tickers'])} tickers × {len(m['vectors'])} vectors "
      f"× {len(m['topologies'])} topologies × {m['reps']} reps · model={m['model']} · "
      f"eval={m['eval_date']} · {m['elapsed_sec']}s_\n")

    # Table 1: ASR by (topology × vector)
    w("\n**Mean ASR by topology × vector** (single-shot baseline vs pipeline):\n\n")
    w("| Topology | " + " | ".join(v.split("_")[0] for v in VEC) + " | mean |\n")
    w("|---|" + "|".join("---" for _ in VEC) + "|---|\n")
    sbv = s["single_asr_by_vector"]
    w("| single | " + " | ".join(f"{sbv.get(v, 0):.2f}" for v in VEC) + " | "
      f"{sum(sbv.values())/len(sbv):.2f} |\n")
    for t in m["topologies"]:
        bt = s["by_topology"][t]
        pbv = bt["pipeline_asr_by_vector"]
        w(f"| {t} | " + " | ".join(f"{pbv.get(v, 0):.2f}" for v in VEC) + f" | {bt['mean_pipeline_asr']:.2f} |\n")

    # Table 2: per-topology delta / survival / rank-order
    w("\n**Amplification, narrative survival, rank-order stability:**\n\n")
    w("| Topology | mean Δ (pipe−single) | narrative survival | Spearman ρ (vs single) |\n")
    w("|---|---|---|---|\n")
    for t in m["topologies"]:
        bt = s["by_topology"][t]
        w(f"| {t} | {bt['mean_delta']:+.2f} | {bt['mean_narrative_survival']:.2f} | {bt['spearman_rank_vs_single']} |\n")

    # auto insight
    amp = {t: s["by_topology"][t]["mean_delta"] for t in m["topologies"]}
    filt = [t for t, v in amp.items() if v < -0.05]
    ampl = [t for t, v in amp.items() if v > 0.05]
    w(f"\n**Auto-summary.** Filtering topologies (Δ<−0.05): {filt or 'none'}; "
      f"amplifying topologies (Δ>+0.05): {ampl or 'none'}. "
      f"Rank-order Spearman vs single: "
      + ", ".join(f"{t}={s['by_topology'][t]['spearman_rank_vs_single']}" for t in m['topologies']) + ".\n")


def section_C(w, tag="single", title="C — End-to-End Economic Impact (single-shot)"):
    d = _load(f"n6_pnl_{tag}")
    if not d:
        w(f"\n_(batch 6 {tag} results not found)_\n")
        return
    s = d["summary"]
    m = d["meta"]
    w(f"\n## {title}\n")
    w(f"\n_window {m['window'][0]}→{m['window'][1]} · inject {m['inject_day']} · "
      f"SPY buy-hold {m['spy_buy_hold_pct']}% · attack={m['attack']} · "
      f"{len(m['tickers'])} tickers × {m['reps']} reps · {m['elapsed_sec']}s_\n")

    w("\n**Attack-induced Δ vs benign (real dollars):**\n\n")
    w("| Ticker | one-shot Δ$ | one-shot ΔmaxDD | persistent Δ$ | persistent ΔmaxDD | induced notional |\n")
    w("|---|---|---|---|---|---|\n")
    per = s["per_ticker"]
    for t in m["tickers"]:
        if t not in per:
            continue
        dv = per[t]["delta_vs_benign"]
        bs = per[t]["by_scenario"]
        o = dv.get("one_shot", {})
        p = dv.get("persistent", {})
        ind = bs.get("persistent", {}).get("induced_notional", bs.get("one_shot", {}).get("induced_notional", 0))
        w(f"| {t} | {o.get('delta_dollars', 0):+.0f} | {o.get('delta_maxDD_pp', 0):+.2f}pp | "
          f"{p.get('delta_dollars', 0):+.0f} | {p.get('delta_maxDD_pp', 0):+.2f}pp | ${ind:.0f} |\n")

    ct = s["cross_ticker"]
    for scen, a in ct.items():
        w(f"\n**{scen} cross-ticker mean:** Δ=${a['mean_delta_dollars']:+.0f} · "
          f"ΔmaxDD={a['mean_delta_maxDD_pp']:+.2f}pp · induced notional ${a['mean_induced_notional']:.0f} "
          f"(n={a['n_tickers']}).\n")


def main():
    parts = []
    w = parts.append
    w("<!-- AUTO-GENERATED by analyze3.py -->\n")
    w("# Batch 5+6 — Multi-Agent Propagation & Economic Impact\n\n")
    section_A(w)
    section_C(w, "single", "C — End-to-End Economic Impact (single-shot trader)")
    section_C(w, "debate", "A×C — End-to-End Economic Impact (debate pipeline trader)")
    OUT.write_text("".join(parts), encoding="utf-8")
    print(f"wrote {OUT}")
    print("".join(parts))


if __name__ == "__main__":
    main()
